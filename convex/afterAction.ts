'use node';

import { v } from 'convex/values';
import { internalAction } from './_generated/server';
import { internal } from './_generated/api';
import { indexIncidentEvent } from './lib/elastic';
import type { Doc } from './_generated/dataModel';

/**
 * requestReport — fires when an incident closes. It is the TRIGGER for the
 * Factory Droid runner (integrations/droid): we POST a signed event; the runner
 * uses the Droid SDK to write the after-action report, open the Jira issue and
 * post its trace back via /droid/report. If no runner is configured we still
 * produce a deterministic report so the user always gets something.
 */
export const requestReport = internalAction({
  args: { incidentId: v.id('incidents') },
  handler: async (ctx, { incidentId }): Promise<void> => {
    const inc: Doc<'incidents'> | null = await ctx.runQuery(internal.incidents.getInternal, { incidentId });
    if (!inc) return;
    const msgs: Doc<'messages'>[] = await ctx.runQuery(internal.incidents.messagesInternal, { incidentId, limit: 200 });
    const alerts: Doc<'alerts'>[] = await ctx.runQuery(internal.alertsQueries.allForIncident, { incidentId });
    const helpers: number = await ctx.runQuery(internal.helpers.enRouteCount, { incidentId });

    const payload = {
      incidentId: String(incidentId),
      incident: {
        situation: inc.situation, protocolId: inc.protocolId, severity: inc.severity, summary: inc.summary,
        openedAt: inc.openedAt, resolvedAt: inc.resolvedAt, resolution: inc.resolution,
        calledEmergency: inc.calledEmergency, calledAt: inc.calledAt, location: inc.locationText ?? (inc.lat != null ? `${inc.lat},${inc.lng}` : null),
        context: inc.context ?? {}, helpersEnRoute: helpers,
      },
      transcript: msgs.map((m) => ({ at: m.at, role: m.role, content: m.content })),
      alerts: alerts.map((a) => ({ channel: a.channel, status: a.status, at: a.at, error: a.error })),
      callbackUrl: `${process.env.CONVEX_SITE_URL ?? ''}/droid/report`,
    };

    await ctx.runMutation(internal.afterActionQueries.setStatus, { incidentId, status: 'generating' });

    const url = process.env.DROID_WEBHOOK_URL;
    if (url) {
      try {
        const body = JSON.stringify(payload);
        const { createHmac } = await import('node:crypto');
        const sig = createHmac('sha256', process.env.DROID_WEBHOOK_SECRET ?? '').update(body).digest('hex');
        const r = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json', 'x-beacon-signature': sig }, body });
        await ctx.runMutation(internal.incidents.recordAlert, { incidentId, channel: 'droid', status: r.ok ? 'sent' : 'failed', payload: { event: 'incident.closed' }, error: r.ok ? undefined : `HTTP ${r.status}` });
        if (r.ok) return; // Droid runner will call back with the report.
      } catch (e) {
        await ctx.runMutation(internal.incidents.recordAlert, { incidentId, channel: 'droid', status: 'failed', payload: { event: 'incident.closed' }, error: (e as Error).message });
      }
    } else {
      await ctx.runMutation(internal.incidents.recordAlert, { incidentId, channel: 'droid', status: 'skipped', payload: { event: 'incident.closed' }, error: 'DROID_WEBHOOK_URL not set' });
    }

    // Deterministic fallback report.
    const md = fallbackReport(payload);
    await ctx.runMutation(internal.afterActionQueries.setReport, { incidentId, markdown: md, agentTrace: [{ at: Date.now(), kind: 'fallback', text: 'Droid runner unavailable; template report generated by Convex.' }] });
    await indexIncidentEvent({ type: 'incident.closed', incidentId: String(incidentId), situation: inc.situation, severity: inc.severity, summary: inc.summary, report: md, durationSec: inc.resolvedAt ? Math.round((inc.resolvedAt - inc.openedAt) / 1000) : null });
  },
});

function fallbackReport(p: { incident: Record<string, unknown>; transcript: Array<{ at: number; role: string; content: string }>; alerts: Array<{ channel: string; status: string }> }): string {
  const i = p.incident as { situation: string; severity: string; summary: string; openedAt: number; resolvedAt?: number; resolution?: string; calledEmergency: boolean };
  const dur = i.resolvedAt ? Math.round((i.resolvedAt - i.openedAt) / 1000) : 0;
  const lines = [
    `# After-action report — ${i.situation.replace(/_/g, ' ')}`,
    '',
    `**Severity:** ${i.severity}  **Duration:** ${Math.floor(dur / 60)}m ${dur % 60}s  **911 called:** ${i.calledEmergency ? 'yes' : 'not confirmed'}`,
    '',
    `## What happened`, i.summary, '',
    `## Timeline`,
    ...p.transcript.filter((m) => m.role !== 'assistant' || true).map((m) => `- ${new Date(m.at).toLocaleTimeString()} — **${m.role}**: ${m.content}`),
    '',
    `## Alerts`, ...p.alerts.map((a) => `- ${a.channel}: ${a.status}`),
    '',
    `## Resolution`, i.resolution ?? 'unknown',
  ];
  return lines.join('\n');
}
